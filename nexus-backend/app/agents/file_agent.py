"""
FileAgent: reads and writes files inside a bounded workspace directory.

Missions carry only a prompt (no uploads), so the target file is taken from a
filename mentioned in the prompt, matched with the Decision Engine's
FILE_REF_RE. Missing or unnamed files are reported as such, never invented.

WRITE_FILE content is generated by the model from the step's purpose and prior
step outputs, then written to disk.

Limitation: the workspace is a single shared directory, so concurrent missions
share one namespace.
"""


import os
import re

from app.services.decision.normalize import FILE_REF_RE
from app.services.llm import llm_available, structured_call
from app.services.planner.models import OperationType
from app.tools.workspace import WORKSPACE, safe_path as _shared_safe_path

from .base_agent import BaseAgent
from .step_execution import CapabilityUnavailableError, StepOutput

MAX_READ_BYTES = 100_000  # Large enough for documents; bounded to fit the model context.

WRITE_SYSTEM = """You are producing the exact content to be written to a file, \
as one step of a larger, already-planned and already-governed mission. Return \
only the file's real content in `output` -- no commentary, no markdown fences \
unless the file itself is markdown. Use `notes` for anything about the write \
itself (e.g. assumptions about format)."""


def _safe_path(filename: str):
    """FileAgent's flat, single-file workspace -- resolves through the shared
    traversal guard, translating its ValueError into this agent's explicit-
    failure type."""
    try:
        return _shared_safe_path(WORKSPACE, filename)
    except ValueError as exc:
        raise CapabilityUnavailableError(str(exc))


def _referenced_files(prompt: str) -> list:
    return list(dict.fromkeys(FILE_REF_RE.findall(prompt.lower())))


class FileAgent(BaseAgent):

    name = "FileAgent"

    def run(self, context):
        return context

    def run_step(self, step, context):
        if step.operation == OperationType.READ_FILE:
            return self._read(step, context)
        if step.operation == OperationType.WRITE_FILE:
            return self._write(step, context)
        if step.operation == OperationType.DELETE_FILE:
            return self._delete(step, context)
        raise CapabilityUnavailableError(
            f"FileAgent has no real implementation for {step.operation.value}."
        )

    def _read(self, step, context) -> str:
        refs = _referenced_files(context.prompt)
        if not refs:
            raise CapabilityUnavailableError(
                "No filename was referenced in the mission prompt -- there is "
                "nothing concrete to read. This system has no file-upload "
                "mechanism; a file must be named explicitly (e.g. 'report.pdf')."
            )

        found, missing = [], []
        for name in refs:
            path = _safe_path(name)
            if path.is_file():
                found.append(path)
            else:
                missing.append(name)

        if not found:
            raise CapabilityUnavailableError(
                f"Referenced file(s) not found in the workspace ({WORKSPACE}): "
                f"{', '.join(missing)}. No file was read."
            )

        chunks = []
        for path in found:
            try:
                content = path.read_text(encoding="utf-8", errors="replace")[:MAX_READ_BYTES]
            except Exception as exc:
                raise CapabilityUnavailableError(
                    f"Found '{path.name}' but could not read it: {exc}"
                )
            chunks.append(f"--- {path.name} ---\n{content}")

        output = "\n\n".join(chunks)
        if missing:
            output += f"\n\n[Note: also referenced but not found: {', '.join(missing)}]"
        return output

    def _write(self, step, context) -> str:
        refs = _referenced_files(context.prompt)
        # In "read X, then write Y", X already exists in the workspace (that is
        # why it could be read) and Y does not yet -- prefer a reference that
        # is not already an existing file, rather than blindly taking the first
        # one named, which would pick the input file as the write target.
        candidates = [r for r in refs if not _safe_path(r).is_file()] or refs
        filename = candidates[0] if candidates else re.sub(r"[^a-z0-9]+", "_", step.action.lower()).strip("_") + ".txt"

        if not llm_available():
            raise CapabilityUnavailableError(
                "WRITE_FILE requires Gemma 4 12B on Ollama to produce real content; "
                "none is configured. No file was written."
            )

        prior = "\n".join(
            f"- [{r['step_id']}] {r['agent']}: {(r.get('output') or '')[:400]}"
            for r in context.step_results if r.get("status") == "completed"
        )
        prompt = f"""Mission objective: {context.prompt}

File to produce: {filename}
Step: {step.action}
Description: {step.description}
Purpose: {step.purpose}

Prior completed step outputs:
{prior or '(none yet)'}

Produce the real content for this file."""

        result = structured_call(WRITE_SYSTEM, prompt, StepOutput, effort="medium")
        if result is None:
            raise CapabilityUnavailableError(
                "The model returned no content for this file."
            )

        path = _safe_path(filename)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(result.output, encoding="utf-8")

        return f"Wrote {len(result.output)} bytes to {path.relative_to(WORKSPACE.parent)}"

    def _delete(self, step, context) -> str:
        # Reachable only if a future governance change relaxes the current
        # upstream hard-block on irreversible-destructive operations -- today
        # HELIX denies any mission containing a DELETE_FILE step before
        # AgentExecutor ever runs, so this code path is unexercised in
        # practice. It is real, not a stub, in case that ever changes.
        refs = _referenced_files(context.prompt)
        if not refs:
            raise CapabilityUnavailableError(
                "No filename was referenced in the mission prompt -- refusing "
                "to guess what to delete."
            )
        path = _safe_path(refs[0])
        if not path.is_file():
            raise CapabilityUnavailableError(
                f"'{refs[0]}' does not exist in the workspace; nothing to delete."
            )
        path.unlink()
        return f"Deleted {path.relative_to(WORKSPACE.parent)}"
